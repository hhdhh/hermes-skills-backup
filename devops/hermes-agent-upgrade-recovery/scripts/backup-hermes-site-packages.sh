#!/bin/bash
# backup-hermes-site-packages.sh
# 一次性把当前 hermes-agent 安装的全部文件打成 backup tar
# 用法：
#   ./backup-hermes-site-packages.sh             # 备份当前 hermes 到 ~/.hermes/backups/<date>-<version>/
#   ./backup-hermes-site-packages.sh --restore-from <path>   # 从 backup 还原
# 兼容：trash 优先，安全第一

set -euo pipefail

PYTHON=${PYTHON:-/Users/kk/miniconda3/bin/python3}
LOCATION=$($PYTHON -m pip show hermes-agent 2>/dev/null | awk '/^Location:/ {print $2}')

if [ -z "$LOCATION" ]; then
  echo "❌ 找不到 hermes-agent pip package。请检查 miniconda 是否激活。"
  exit 1
fi

VERSION=$($PYTHON -m pip show hermes-agent 2>/dev/null | awk '/^Version:/ {print $2}')
TIMESTAMP=$(date +%Y%m%d-%H%M%S)
BACKUP_BASE="${HOME}/.hermes/backups"
BACKUP_DIR="${BACKUP_BASE}/${TIMESTAMP}-${VERSION}"

mkdir -p "$BACKUP_DIR"

# --- 备份模式 ---
if [ "${1:-}" = "--restore-from" ]; then
  SRC="${2:?restore-from 需要 backup tar.gz 路径}"
  if [ ! -f "$SRC" ]; then
    echo "❌ backup tar 不存在：$SRC"
    exit 1
  fi
  echo "🚨 即将从 $SRC 还原到 $LOCATION/"
  echo "   当前 hermes-agent 版本：$VERSION"
  echo "   Press <Enter> 继续，或 Ctrl-C 取消"
  read -r
  tar -xzf "$SRC" -C "$LOCATION/"
  echo "✓ 还原完成。再跑一次 \$PYTHON -m pip install --upgrade --force-reinstall hermes-agent==<version> 让 dist-info 对齐"
  exit 0
fi

# --- 默认：备份当前 ---
cd "$LOCATION"

# 1. 找顶层 hermes_* 模块 + hermes_cli 包
PACKAGES="hermes_cli"
for f in hermes_*.py; do
  if [ -f "$f" ]; then
    PACKAGES="$PACKAGES $f"
  fi
done

# 2. 找所有 dist-info（含 hermes_agent-VERSION.dist-info 真实包名）
DIST_INFO_DIRS=$(ls -d hermes_agent-*.dist-info 2>/dev/null || true)

if [ -z "$PACKAGES" ] && [ -z "$DIST_INFO_DIRS" ]; then
  echo "❌ site-packages 里找不到 hermes 相关文件，请检查："
  echo "   location: $LOCATION"
  echo "   contents:"
  ls "$LOCATION/" | grep -i hermes || echo "   (空)"
  exit 1
fi

TAR_FILE="$BACKUP_DIR/hermes_${VERSION}_full.tar.gz"

# 3. 打包
tar -czf "$TAR_FILE" \
    $PACKAGES \
    $DIST_INFO_DIRS

# 4. 同时备份 config
cp ~/.hermes/config.yaml "$BACKUP_DIR/config.yaml.bak" 2>/dev/null || true
cp ~/.hermes/.env "$BACKUP_DIR/.env.bak" 2>/dev/null || true

# 5. 验证
SIZE=$(du -h "$TAR_FILE" | awk '{print $1}')

echo "✓ 备份完成"
echo "  backup tar: $TAR_FILE ($SIZE)"
echo "  backup dir: $BACKUP_DIR"
echo
echo "📝 备份内容："
tar -tzf "$TAR_FILE" | head -20
echo "  ... ($(tar -tzf "$TAR_FILE" | wc -l | tr -d ' ') entries total)"
echo
echo "还原方法："
echo "  $0 --restore-from $TAR_FILE"
echo "  # 或 1 行回滚："
echo "  tar -xzf $TAR_FILE -C $LOCATION/ && $PYTHON -m pip install --upgrade --force-reinstall hermes-agent==$VERSION"
